#!/usr/bin/env python3
"""embed.py - generate a C file that contains program images, so they ship inside the kernel.

    embed.py out.c /bin/hello.exe=build/user/hello.exe ...
"""
import sys

out = sys.argv[1]
items = [a.split('=', 1) for a in sys.argv[2:]]
with open(out, 'w') as f:
    f.write('/* generated by tools/embed.py - do not edit */\n#include "embedded.h"\n\n')
    for i, (dest, src) in enumerate(items):
        data = open(src, 'rb').read()
        f.write('static const unsigned char file%d[] = {' % i)
        f.write(','.join(str(b) for b in data))
        f.write('};\n')
    f.write('\nconst struct embedded_file embedded_files[] = {\n')
    for i, (dest, src) in enumerate(items):
        f.write('    { "%s", file%d, sizeof(file%d) },\n' % (dest, i, i))
    if not items:
        f.write('    { 0, 0, 0 }\n')
    f.write('};\nconst unsigned embedded_count = %d;\n' % len(items))
